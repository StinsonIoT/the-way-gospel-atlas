const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const values = new Map(), storage = () => ({ getItem: k => values.get(k) || null, setItem: (k, v) => values.set(k, v), removeItem: k => values.delete(k) });
const context = { window: {} }; vm.createContext(context);
for (const module of ['session', 'player', 'journal']) vm.runInContext(fs.readFileSync('js/' + module + '.js', 'utf8'), context);
const scenes = [{ id: 'title' }, { id: 'a' }, { id: 'b' }, { id: 'c' }, { id: 'd' }];
const days = [{ steps: [1, 2] }, { steps: [3, 4] }];
const session = context.window.WAY_SESSION.create(scenes, days, storage);
assert(session.startDay(1)); session.visit(3); assert.equal(session.adjacent(-1), null); assert.equal(session.adjacent(1), 4);
assert.equal(session.adjacent(1, [1, 2]), null, 'A Gospel intersection cannot escape the day');
assert.equal(session.completed.size, 0, 'Visiting is distinct from completion');
assert(session.finishDay().saved); session.setMode('reading');
const restored = context.window.WAY_SESSION.create(scenes, days, storage);
assert.equal(restored.day, 1); assert.equal(restored.mode, 'reading'); assert(restored.completed.has(1));
restored.leaveDay(); assert.equal(restored.day, null);
const player = context.window.WAY_PLAYER.create(scenes);
assert.equal(player.configure({ start: 3, end: 4, scope: [3, 4], allowed: [1, 2] }), null);
assert(player.configure({ start: 3, end: 4, scope: [3, 4] }));
assert.equal(player.previous(3), -1); assert.equal(player.next(4), -1); assert.equal(player.next(3), 4);
assert.equal(player.configure({ start: 3, end: 4, scope: [4, 3] }), null, 'Malformed scope rejected without changing the current scope');
assert.equal(player.previous(3), -1);
const segment = { start: 100, end: 160 };
assert.equal(context.window.WAY_PLAYER.progress(segment, 115, NaN).elapsed, 15);
assert.equal(context.window.WAY_PLAYER.progress({ start: 100, end: null }, 115, NaN).duration, null);
assert.equal(context.window.WAY_PLAYER.seek({ start: 100, end: null }, 15, Infinity), null);
assert(context.window.WAY_PLAYER.seek(segment, 90, NaN) < 160); assert.equal(context.window.WAY_PLAYER.seek(segment, -5, NaN), 100);
const journal = context.window.WAY_JOURNAL.create(storage);
journal.edit('a', '<script>user text</script>'); journal.save('a');
const data = journal.exportData(scenes, new Set(['b']), s => s.id);
assert.equal(data.reflections[0].text, '<script>user text</script>'); assert.equal(data.savedScenes[0].scene, 'b');
assert(journal.markdown(data).includes('## a'));
const denied = context.window.WAY_JOURNAL.create(() => { throw Error('denied'); });
denied.edit('a', 'Keep my draft'); assert(denied.save('a').status.includes('Could not save')); assert.equal(denied.get('a').value, 'Keep my draft');
assert.throws(() => denied.exportData(scenes, new Set(), s => s.id));
assert(journal.clear(scenes)); assert.equal(journal.list(scenes).notes.length, 0);
console.log('PASS: day and Gospel boundaries, explicit completion, persisted reading preference, bounded playback and seeking, journal exports and denied storage.');
