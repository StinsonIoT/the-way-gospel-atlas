const assert = require('node:assert/strict');
const { load } = require('./helpers/globals.cjs');
const J = load('js/journey.js', 'WAY_JOURNEY');
const scenes = ['title','word','birth','close'].map(id => ({id}));
const days = [['First',['word']],['Second',['birth','close']]];
const state = { scenes, days, readingId:'birth', listening:{scene:'word'}, preferredMode:'reading', seenIds:[], savedIds:[] };
assert.equal(J.snapshot(state).primary.scene, 'birth');
assert.equal(J.snapshot({...state, preferredMode:'listening'}).primary.scene, 'word');
assert.equal(J.snapshot({...state, preferredMode:'invalid'}).primary.mode, 'listening');
assert.equal(J.snapshot({...state, readingId:'gone'}).primary.mode, 'listening');
assert.equal(J.snapshot({...state, readingId:'gone', listening:{scene:'gone'}}).primary, null);
assert.equal(J.snapshot({...state, readingId:'word', listening:null}).primary.scene, 'word');
assert.equal(J.snapshot({...state, seenIds:['word','birth','close']}).nextDay, null);
assert.equal(J.nextDay(days,['word','birth']), 1);
assert.equal(J.rememberMode('reading',{setItem(){throw Error('denied')}}), false);
assert.equal(J.rememberMode('other',{setItem(){throw Error('must not call')}}), false);
const plain = x => JSON.parse(JSON.stringify(x));
assert.deepEqual(plain(J.planRange(['word','birth'],scenes,['birth'])),{indices:[2],start:2,end:2});
assert.deepEqual(plain(J.planRange(['birth','word','word'],scenes)),{indices:[1,2],start:1,end:2});
assert.equal(J.planRange(['word'],scenes,['birth']),null);
assert.equal(J.planRange(['gone'],scenes),null);
for(const invalid of [null,{},'bad',7]) assert.doesNotThrow(()=>J.snapshot({...state,seenIds:invalid,savedIds:invalid}));
console.log('PASS: independent continuation, validated legacy state, denied storage, exact plan ranges and next-day selection.');
