// Build conservative, recording-specific pause corrections from the MP3 scan.
// Boundaries without a nearby sustained pause retain the provider's timestamp.
const fs = require('node:fs');
const audit = JSON.parse(fs.readFileSync('docs/audio-waveform-audit.json', 'utf8'));
if (!audit.complete) throw Error('Run the complete --inspect-tour waveform audit first');
const corrections = {};
for (const row of audit.results) {
  for (const [scan, verse] of [[row.startScan, row.from], [row.endScan, row.to + 1]]) {
    if (!scan.gap || scan.candidate == null) continue;
    const shift = scan.time - scan.candidate;
    if (shift < .05 || shift > .3) continue;
    const key = [audit.reader, row.book, row.chapter, verse].join(':');
    corrections[key] = [scan.time, scan.candidate];
  }
}
// These three boundaries were separately inspected in the opening/origins
// waveform windows and exercised with real media playback.
corrections['souer:JHN:1:2'] = [10.993, 10.85];
corrections['souer:JHN:1:6'] = [28.725, 28.575];
corrections['souer:LUK:1:39'] = [270.381, 270.15];
const sorted = Object.fromEntries(Object.entries(corrections).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync('js/audio-boundaries.js', '// Souer BSB MP3 pause corrections; original timestamps guard against provider changes.\n// Generated by tools/make-audio-boundaries.cjs. See docs/audio-waveform-audit.json.\nwindow.WAY_AUDIO_GAPS = ' + JSON.stringify(sorted, null, 2) + ';\n');
console.log('Wrote', Object.keys(sorted).length, 'recording-specific boundary corrections');
